// Μικροί βοηθοί για τα κείμενα της ΗΚΑΙ: άρθρο μπροστά από τον τιμωρήσαντα, πατρώνυμο σε γενική (-ΟΣ, -ΗΣ, -ΑΣ).
// Ό,τι δεν ταιριάζει (θηλυκά, -ΟΥ, συντομογραφίες χωρίς κατάληξη) μένει όπως γράφτηκε.
import { upper } from './text';

// Λέξεις σε γενική που συνοδεύουν βαθμό ή θέση («ΔΚΤΗΣ ΙΛΗΣ», «ΑΞΚΟΣ ΥΠΗΡΕΣΙΑΣ»): δεν κλίνονται
const KEEP = new Set(['ΙΛΗΣ', 'ΕΠΧΙΑΣ', 'ΜΟΝΑΔΑΣ', 'ΜΟΝΑΔΟΣ', 'ΜΟΙΡΑΣ', 'ΤΑΞΙΑΡΧΙΑΣ', 'ΤΑΞΗΣ', 'ΔΙΜΟΙΡΙΑΣ', 'ΥΠΗΡΕΣΙΑΣ', 'ΣΧΟΛΗΣ', 'ΔΙΟΙΚΗΣΗΣ',
  'ΕΚΠΑΙΔΕΥΣΗΣ', 'ΦΡΟΥΡΑΣ', 'ΠΥΡΟΒΟΛΑΡΧΙΑΣ', 'ΠΥΡΟΣΒΕΣΤΙΚΗΣ', 'ΤΗΣ', 'ΤΟΥ']);
const words = (s: string) => upper(s).trim().replace(/\s+/g, ' ').split(' ');
// η πρώτη λέξη (ο βαθμός) κλίνεται πάντα: «ΕΠΧΙΑΣ ΔΟΚΙΜΙΟΣ» είναι ο επιλοχίας, «ΔΚΤΗΣ ΕΠΧΙΑΣ» η επιλαρχία
const greek = (w: string, i: number) => w.length >= 3 && /^[Α-ΩΪΫ]+$/.test(w) && (i === 0 || !KEEP.has(w));

// Ο τιμωρήσας γράφεται όπως τον έγραψες, σε αιτιατική (Michael, 17/10: «θα εισάγουμε τα στελέχη στην αιτιατική»).
// Μπαίνει μόνο το «ΤΟΝ» μπροστά, εκτός αν γράφτηκε ήδη με άρθρο («την ΛΧΙΑ …»).
export function withArticle(s: string): string {
  const w = words(s); if (!w[0]) return '';
  return (/^(ΤΟΝ|ΤΗΝ|ΤΟ|ΤΟΥΣ|ΤΙΣ)$/.test(w[0]) && w.length > 1 ? '' : 'ΤΟΝ ') + w.join(' ');
}
// Πατρώνυμο σε γενική: «ΓΕΩΡΓΙΟΣ» → «ΓΕΩΡΓΙΟΥ», «ΙΩΑΝΝΗΣ» → «ΙΩΑΝΝΗ», «ΑΝΔΡΕΑΣ» → «ΑΝΔΡΕΑ» (ό,τι είναι ήδη σε γενική μένει)
export function genitive(s: string): string {
  const w = words(s); if (!w[0]) return '';
  return w.map((x, i) => (!greek(x, i) ? x : x.endsWith('ΟΣ') ? x.slice(0, -2) + 'ΟΥ' : /(ΗΣ|ΑΣ)$/.test(x) ? x.slice(0, -1) : x)).join(' ');
}
