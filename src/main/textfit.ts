const PX = 96 / 72;
// Πλάτος σε pixel (96 dpi) με λίγο περιθώριο ασφαλείας: καλύτερα λίγο μικρότερα γράμματα παρά κομμένα
export function textPx(t: string, f: FontSpec): number {
  const w = W[(family(f.name) + (f.b ? 'B' : '')) as Fam];
  let em = 0; for (const ch of t) { const i = AT.get(ch); em += i == null ? 72 : w[i]; }
  return (em / 100) * f.sz * PX * 1.04;
}
// Πλάτος του ψηφίου «0» της βασικής γραμματοσειράς: η μονάδα των πλατών στήλης του Excel
export const digitPx = (f: FontSpec) => Math.max(5, Math.round(textPx('0', f) / 1.04));
const lineH = (f: FontSpec) => f.sz * LINE[family(f.name)];
// Γραμμές με αναδίπλωση στα κενά· Infinity αν μια λέξη δεν χωράει μόνη της στο πλάτος (cut: τότε κόβεται σε όσες γραμμές
// χρειάζεται, όπως κάνει ο Excel με λέξη μεγαλύτερη από τη στήλη)
export function linesOf(t: string, f: FontSpec, w: number, cut = false): number {
  let n = 0;
  for (const para of t.split('\n')) {
    let cur = 0; n++;
    // αλλαγή γραμμής στα κενά και μετά από παύλα (ΧΑΤΖΗΓΕΩΡΓΙΑΔΗΣ-|ΚΩΝΣΤΑΝΤΙΝΙΔΗΣ), όπως στο Excel
    for (const tok of para.split(/(?<= )|(?<=-)/)) {
      const word = tok.trimEnd(); const x = textPx(word, f); const sp = tok.length > word.length ? textPx(' ', f) : 0;
      if (x > w) {
        if (!cut) return Infinity;
        if (cur) n++;
        const k = Math.ceil(x / w); n += k - 1; cur = x - (k - 1) * w + sp; continue;
      }
      if (cur && cur + x > w) { n++; cur = 0; }
      cur += x + sp;
    }
  }
  return n;
}
const PAD = 2;   // pt πάνω και κάτω μέσα στο κελί
export interface Box { w: number; h: number; wrap: boolean; num?: boolean }   // πλάτος σε px, ύψος σε pt
export interface Fit { sz: number; wrap: boolean; grow: number }               // grow: pt που πρέπει να ψηλώσει η γραμμή
// Μικρότερο μέγεθος γραμμάτων που δεχόμαστε πριν ψηλώσει η γραμμή: τα 3/4 του αρχικού, όχι κάτω από 7
export const minSize = (sz: number) => Math.min(sz, Math.max(7, Math.round(sz * 1.5) / 2));
// Πώς χωράει: πρώτα σε μία γραμμή με λίγο μικρότερα γράμματα (ως το minSize), ή σε περισσότερες γραμμές στο ύψος που έχει
// ήδη το κελί· αλλιώς αναδίπλωση και ψηλότερη γραμμή. Μόνο όταν μια λέξη δεν χωράει ούτε έτσι μικραίνει κι άλλο.
// null: χωράει όπως είναι. min: κάτω όριο (για ομάδα κελιών που ξεκινά ήδη από μικρότερο μέγεθος).
export function fitText(t: string, f: FontSpec, box: Box, min = minSize(f.sz)): Fit | null {
  const nl = t.includes('\n');
  const at = (sz: number): FontSpec => ({ ...f, sz });
  const one = (sz: number) => !nl && textPx(t, at(sz)) <= box.w;
  const tall = (sz: number) => { const n = linesOf(t, at(sz), box.w); return n === 1 ? 0 : n * lineH(at(sz)) + PAD; };
  const inBox = (sz: number) => tall(sz) <= box.h;
  if (box.wrap ? inBox(f.sz) : one(f.sz)) return null;
  if (box.num) {   // αριθμός (ή ημερομηνία): δεν αναδιπλώνεται, μόνο μικραίνει
    const s = Math.floor((f.sz * box.w) / textPx(t, f) * 2) / 2;
    return { sz: Math.max(5, Math.min(f.sz, s)), wrap: box.wrap, grow: 0 };
  }
  for (let s = f.sz; s >= min - 1e-9; s -= 0.5) {
    if (s !== f.sz && one(s)) return { sz: s, wrap: box.wrap, grow: 0 };
    if (inBox(s)) return { sz: s, wrap: true, grow: 0 };
  }
  // ψηλότερη γραμμή: στο μικρότερο μέγεθος (λιγότερες γραμμές). Λέξη που δεν χωράει ούτε έτσι: μόνη της μικραίνει όσο
  // χρειάζεται· μέσα σε κείμενο ως τα 6 και μετά κόβεται σε γραμμές.
  let s = Math.min(f.sz, min);
  if (!isFinite(linesOf(t, at(s), box.w))) {
    const widest = Math.max(...t.split(/[\n ]|(?<=-)/).map(x => textPx(x, f)));
    const fits = Math.floor((f.sz * box.w) / widest * 2) / 2;
    if (!/[\n -]/.test(t)) return { sz: Math.max(5, fits), wrap: box.wrap, grow: 0 };
    s = Math.max(6, Math.min(s, fits));
  }
  const n = linesOf(t, at(s), box.w, true);
  const need = n > 1 ? n * lineH(at(s)) + PAD : 0;
  return { sz: s, wrap: box.wrap || n > 1, grow: Math.max(0, Math.ceil((need - box.h) * 4) / 4) };
}
