// Coverage table of the 75 Dialog/Sheet sites (Appendix ΣΤ): which snapshot shows each, or why none does.
//
// Purpose: make "every dialog is in the net" checkable. The table is generated from data
//   (test/support/dialog-sites.ts + the render cases) and stored as test/__snapshots__/screens/COVERAGE.md.
// Fails when: a site has neither a snapshot case nor a reason; a case names an unknown site; a snapshot file named by a
//   case is missing; or the stored COVERAGE.md differs (update with `npx vitest run -u`, only in a PR that
//   deliberately adds or moves dialogs).
// Does NOT: render anything (the cases are rendered by screens-dialogs-shell/forms.test.ts).
import { describe, expect, it } from 'vitest';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { SITES, NOT_COVERED } from './support/dialog-sites';
import { SHELL_CASES } from './support/dialog-cases-shell';
import { FORMS_CASES } from './support/dialog-cases-forms';

const CASES = [...SHELL_CASES, ...FORMS_CASES];
const snapshotsOf = (site: string): string[] =>
  CASES.filter(c => c.sites.includes(site)).map(c => 'dialog-' + c.name + '.html');

function table(): string {
  const covered = SITES.filter(s => snapshotsOf(s.site).length > 0);
  const rows = SITES.map(s => {
    const files = snapshotsOf(s.site);
    const how = files.length ? files.map(f => '`' + f + '`').join(', ') : 'NOT covered: ' + NOT_COVERED[s.site];
    const title = s.title.replace(/\|/g, '\\|');
    return '| `' + s.site + '` | `' + s.component + '` | ' + s.kind + ' | ' + title + ' | ' + how + ' |';
  });
  return [
    '# Dialog and sheet coverage of the screen HTML snapshots',
    '',
    'Generated by `test/screens-dialogs-coverage.test.ts` from `test/support/dialog-sites.ts` and the render cases.',
    'Do not edit by hand; update with `npx vitest run -u` in a PR that adds or moves a dialog.',
    'Snapshots are the FIRST render of the component in its open state (react-dom/server: effects do not run).',
    'Sites marked NOT covered open only after a click (local `useState`) or after an effect; the browser DOM snapshot',
    '(Phase 0.3b, `bench/ui/styles-diff.mjs`) opens them in Electron.',
    '',
    '**Covered: ' + covered.length + ' of ' + SITES.length + '.** Screens, tabs and the app shell are in',
    '`screen-*.html` and `tab-*.html`.',
    '',
    '| Site | Component | Kind | Title | Snapshot |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    '## Tabs and screens not selectable by nav params (local `useState`), not covered',
    '',
    '- Υπηρεσίες (GuardScreen): tabs Θέσεις (default, covered), Ποιος κάνει τι, Εξαιρέσεις, Excel (mobile) and the',
    '  Λίστα / Μηνιαίο πλέγμα switch of the check. Only the `WhoDoes` and `SkipsView` components are rendered on their',
    '  own (`tab-guard--whodoes`, `tab-guard--skips`).',
    '- ΗΚΑΙ main page: sides Μπροστά / Πίσω / Σύνοψη (local `side`); the default side is in `screen-hkai`.',
    '- Καρτέλα ατόμου (PersonSheet): tabs Υπηρεσίες, Ιστορικό, Σημειώσεις, Προσωπικά (local `tab`;',
    '  Στοιχεία is covered).',
    '- Καρτέλα στελέχους (CadreSheet): tabs Στοιχεία, Σημειώσεις, Προσωπικά (local `tab`; Καταστάσεις is covered).',
    '- Εξοδούχοι: sort Ανά θάλαμο / Αλφαβητικά; Ιστορικό: source filter; Έντυπα: wizard steps and editors',
    '  (state of the page, loaded by effects); Ρυθμίσεις cards with their own segmented controls.',
    '- Διάγνωση: numbers are loaded in an effect, the snapshot shows the loading state.',
    '',
  ].join('\n');
}

describe('dialog coverage table', () => {
  it('every site is covered by a snapshot case or has a reason, never both', () => {
    const bad = SITES.filter(s => (snapshotsOf(s.site).length > 0) === (s.site in NOT_COVERED)).map(s => s.site);
    expect(bad).toEqual([]);
  });
  it('the list has the 75 sites of Appendix ΣΤ', () => { expect(SITES).toHaveLength(75); });
  it('cases and reasons only name known sites; case names are unique', () => {
    const known = new Set(SITES.map(s => s.site));
    expect(CASES.flatMap(c => c.sites).filter(s => !known.has(s))).toEqual([]);
    expect(Object.keys(NOT_COVERED).filter(s => !known.has(s))).toEqual([]);
    expect(new Set(CASES.map(c => c.name)).size).toBe(CASES.length);
  });
  it('every snapshot named by a case exists', () => {
    const dir = join(__dirname, '__snapshots__', 'screens');
    expect(CASES.map(c => 'dialog-' + c.name + '.html').filter(f => !existsSync(join(dir, f)))).toEqual([]);
  });
  it('COVERAGE.md is up to date', async () => {
    await expect(table()).toMatchFileSnapshot('./__snapshots__/screens/COVERAGE.md');
  });
});
