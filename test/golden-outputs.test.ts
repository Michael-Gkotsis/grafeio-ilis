/**
 * Golden outputs: every Excel/Word file the app writes, and its print rendering, must stay byte-identical (CLAUDE.md,
 * hard rule 1). This test regenerates a content hash for each output and compares it, line by line, with the committed
 * baseline `test/golden/outputs.txt` (one line per output: `<key> <hash>`). A failure names every changed output.
 *
 * What is covered (generation code: bench/golden-lib.ts, golden-books.ts, golden-writeback.ts), 5, 60 and 300 people:
 *  - report presets (Excel, preview, 4 print layouts), the ΦΡΟΥΡΑ / ΗΚΑΙ / Εξοδούχοι forms and their variants
 *    (ΦΡΟΥΡΑ ΣΠΕΝ, ΠΣΚ merges, «Όλη η δύναμη», custom signatures)
 *  - Δυναμολόγιο lists (all filters), ΣΥΝΟΛΙΚΟ, preview, ΣΤΕΛΕΧΗ, Οπλισμός, Ημερολόγιο κωλυομένων, έλεγχος υπηρεσιών,
 *    each raw, signed (as the app delivers it) and printed
 *  - Ημερήσια Διαταγή as Word (.docx) and as Excel
 *  - write-backs into the unit's Excel files (create, edit person fields, new sheets, foreign workbook, placed sheets)
 *
 * What it does NOT do: it does not judge whether an output is "right" (other tests do), it does not open the files in
 * Excel/Word, and it never updates the baseline on its own.
 *
 * How the hashes are made stable:
 *  - The clock is fixed (Date only) to 2026-10-22 10:30 local time; data comes from the seeded `benchState`.
 *  - A file hash is the SHA-1 of every zip part name and its uncompressed bytes. EXCLUDED, because it is container
 *    metadata and not content: zip entry timestamps, compression level and entry order (JSZip stamps "now" on entries
 *    the app builds itself, e.g. the built-in Word template). Nothing else is stripped: docProps/core.xml, rsids and
 *    all XML parts are hashed in full (the app already writes fixed dates there).
 *  - Write-back results also return file mtimes (volatile); only the written file content is hashed, from temp folders
 *    with random names, so a path or time inside a file would show up as an unstable hash.
 *
 * Update the baseline after an INTENDED output change (a written behavior change, never during a refactor PR):
 *   GOLDEN_UPDATE=1 npx vitest run test/golden-outputs.test.ts
 * then review `git diff test/golden/outputs.txt`. Updating is refused when `CI` is set.
 * Check time-zone independence with `TZ=UTC` and `TZ=Europe/Athens` in front of the same command.
 *
 * Owner layer: tests. Why: the rewrite must not change outputs; `npm run bench:golden` only printed hashes.
 */
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
import fs from 'fs';
import path from 'path';
import { GOLDEN_SIZES, goldenState, legacyRows, type GoldenEntry } from '../bench/golden-lib';
import { formVariantEntries, hdEntries, madeBookEntries } from '../bench/golden-books';
import { writebackEntries } from '../bench/golden-writeback';

const BASELINE = path.join(__dirname, 'golden', 'outputs.txt');
const HEADER = '# Golden hashes of every Excel/Word output and its print rendering. One line: <key> <hash>.\n'
  + '# Generated by test/golden-outputs.test.ts. Rewrite only with GOLDEN_UPDATE=1 (see the header of that file).\n';
/** Sizes with write-backs: the 300-person write-back adds time but no new code path. */
const WRITEBACK_SIZES = [5, 60];

/** Every golden entry, in a fixed order. */
async function generate(): Promise<GoldenEntry[]> {
  const entries: GoldenEntry[] = [];
  for (const n of GOLDEN_SIZES) {
    const state = goldenState(n);
    entries.push(...(await legacyRows(n)).flatMap(row => row.entries));
    entries.push(...await formVariantEntries(state, n));
    entries.push(...await madeBookEntries(state, n));
    entries.push(...await hdEntries(state, n));
    if (WRITEBACK_SIZES.includes(n)) entries.push(...await writebackEntries(state, n));
  }
  return entries;
}

/** Parse a baseline file into key -> hash; comment (`#`) and blank lines are ignored. */
function parseBaseline(text: string): Map<string, string> {
  return new Map(text.split('\n').filter(line => line.trim() && !line.startsWith('#')).map((line): [string, string] => {
    const at = line.lastIndexOf(' ');
    return [line.slice(0, at), line.slice(at + 1)];
  }));
}

/** Human-readable difference between the baseline and the regenerated outputs; empty when identical. */
function describeDiff(baseline: Map<string, string>, actual: Map<string, string>): string {
  const changed = [...actual].filter(([key, hash]) => baseline.has(key) && baseline.get(key) !== hash)
    .map(([key, hash]) => '  CHANGED  ' + key + '  ' + baseline.get(key) + ' -> ' + hash);
  const added = [...actual.keys()].filter(key => !baseline.has(key)).map(key => '  NEW (not in baseline)  ' + key);
  const gone = [...baseline.keys()].filter(key => !actual.has(key))
    .map(key => '  MISSING (no longer produced)  ' + key);
  const all = [...changed, ...added, ...gone];
  return all.length ? all.length + ' golden output(s) differ from test/golden/outputs.txt:\n' + all.join('\n')
    + '\nIf this change is intended, regenerate with GOLDEN_UPDATE=1 npx vitest run test/golden-outputs.test.ts'
    + ' and review the diff.' : '';
}

describe('golden outputs (Excel, Word, print) stay identical', () => {
  let entries: GoldenEntry[] = [];
  beforeAll(async () => {
    // only Date is faked: timers and promises keep running. Local time on purpose: same wall clock in every TZ.
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(2026, 9, 22, 10, 30, 0));
    entries = await generate();
  }, 300_000);
  afterAll(() => { vi.useRealTimers(); });

  it('every output key is unique', () => {
    const keys = entries.map(e => e.key);
    expect(keys.filter((key, i) => keys.indexOf(key) !== i)).toEqual([]);
  });

  it('every hash equals the committed baseline', () => {
    const text = HEADER + entries.map(e => e.key + ' ' + e.hash).join('\n') + '\n';
    if (process.env.GOLDEN_UPDATE) {
      if (process.env.CI) throw new Error('GOLDEN_UPDATE is not allowed in CI: a person rewrites the baseline');
      fs.mkdirSync(path.dirname(BASELINE), { recursive: true }); fs.writeFileSync(BASELINE, text);
      return;
    }
    expect(fs.existsSync(BASELINE), 'missing ' + BASELINE + ': create it with GOLDEN_UPDATE=1').toBe(true);
    const actual = new Map(entries.map((e): [string, string] => [e.key, e.hash]));
    const diff = describeDiff(parseBaseline(fs.readFileSync(BASELINE, 'utf8')), actual);
    if (diff) throw new Error(diff);
  });
});
